BEGIN;

-- ── 0009 · Etapa 3: "En centro Pokémon" ─────────────────────────────
-- Sin él (por defecto, false) el entrenador no mueve, libera ni transfiere
-- Pokémon de su cinturón y Femputadora. Lo marca el DM por jugador.
ALTER TABLE juego.personaje
  ADD COLUMN IF NOT EXISTS personaje_en_centro_pokemon boolean NOT NULL DEFAULT false;

-- ── 0010 · Etapa 4: intervenciones, XP y reparto ────────────────────
-- Quién intervino contra cada Pokémon del DM (ataque o Poké Ball). id_campo
-- no es clave foránea a propósito: al derrotarlo o atraparlo la fila del
-- campo se borra y la intervención tiene que seguir para repartir la XP.
CREATE TABLE IF NOT EXISTS juego.partida_intervencion (
  id_intervencion      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_partida           integer NOT NULL REFERENCES juego.partida(id_partida) ON DELETE CASCADE,
  id_campo             integer NOT NULL,
  id_personaje         integer NOT NULL REFERENCES juego.personaje(id_personaje) ON DELETE CASCADE,
  id_personaje_pokemon integer REFERENCES juego.personaje_pokemon(id_personaje_pokemon) ON DELETE SET NULL,
  intervencion_tipo    text NOT NULL CHECK (intervencion_tipo IN ('ataque', 'pokebola')),
  created_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS partida_intervencion_campo_idx
  ON juego.partida_intervencion (id_partida, id_campo);

-- La XP de un Pokémon derrotado o atrapado. Estado: pendiente (espera al DM),
-- confirmada (repartida entre entrenadores) o manual (el DM la cerró).
CREATE TABLE IF NOT EXISTS juego.partida_xp (
  id_xp        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_partida   integer NOT NULL REFERENCES juego.partida(id_partida) ON DELETE CASCADE,
  id_campo     integer NOT NULL,
  xp_pokemon   text    NOT NULL,
  xp_nivel     integer NOT NULL,
  xp_sr        text,
  xp_motivo    text    NOT NULL CHECK (xp_motivo IN ('derrota', 'captura')),
  xp_total     integer NOT NULL CHECK (xp_total >= 0),
  xp_estado    text    NOT NULL DEFAULT 'pendiente' CHECK (xp_estado IN ('pendiente', 'confirmada', 'manual')),
  created_at   timestamptz NOT NULL DEFAULT now(),
  resuelta_at  timestamptz
);
CREATE INDEX IF NOT EXISTS partida_xp_pendiente_idx
  ON juego.partida_xp (id_partida, xp_estado);

-- La parte de cada entrenador; asignada_at null = aún no la reparte (le
-- vuelve a salir al entrar, aunque se le haya caído la sesión).
CREATE TABLE IF NOT EXISTS juego.partida_xp_reparto (
  id_reparto    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_xp         integer NOT NULL REFERENCES juego.partida_xp(id_xp) ON DELETE CASCADE,
  id_personaje  integer NOT NULL REFERENCES juego.personaje(id_personaje) ON DELETE CASCADE,
  reparto_xp    integer NOT NULL CHECK (reparto_xp >= 0),
  asignada_at   timestamptz,
  CONSTRAINT partida_xp_reparto_unico UNIQUE (id_xp, id_personaje)
);
CREATE INDEX IF NOT EXISTS partida_xp_reparto_personaje_idx
  ON juego.partida_xp_reparto (id_personaje) WHERE asignada_at IS NULL;

-- ── 0011 + 0012 · Etapa 4: ganancias guardadas ──────────────────────
-- Una ganancia de XP sube como máximo un nivel y lo que sobra se pierde.
-- Solo se guarda una ganancia ENTERA cuando el Pokémon tiene mejoras de nivel
-- por completar; una fila por ganancia, para que no se junten.
CREATE TABLE IF NOT EXISTS juego.personaje_pokemon_xp_guardada (
  id_xp_guardada       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_personaje_pokemon integer NOT NULL
    REFERENCES juego.personaje_pokemon(id_personaje_pokemon) ON DELETE CASCADE,
  xp_guardada          integer NOT NULL CHECK (xp_guardada > 0),
  updated_at           timestamptz NOT NULL DEFAULT now()
);
-- Por si la tabla ya existía con la forma vieja (una fila por Pokémon)
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
      FROM information_schema.table_constraints tc
      JOIN information_schema.key_column_usage k
        ON k.constraint_name = tc.constraint_name AND k.table_schema = tc.table_schema
     WHERE tc.table_schema = 'juego' AND tc.table_name = 'personaje_pokemon_xp_guardada'
       AND tc.constraint_type = 'PRIMARY KEY' AND k.column_name = 'id_personaje_pokemon'
  ) THEN
    ALTER TABLE juego.personaje_pokemon_xp_guardada DROP CONSTRAINT personaje_pokemon_xp_guardada_pkey;
  END IF;
END $$;
ALTER TABLE juego.personaje_pokemon_xp_guardada
  ADD COLUMN IF NOT EXISTS id_xp_guardada integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
CREATE INDEX IF NOT EXISTS personaje_pokemon_xp_guardada_pokemon_idx
  ON juego.personaje_pokemon_xp_guardada (id_personaje_pokemon);

-- ── Registro de migraciones aplicadas ───────────────────────────────
CREATE TABLE IF NOT EXISTS juego.schema_migrations (
  name        text PRIMARY KEY,
  applied_at  timestamptz NOT NULL DEFAULT now()
);
INSERT INTO juego.schema_migrations (name) VALUES
  ('0009_personaje_centro_pokemon.sql'),
  ('0010_partida_xp.sql'),
  ('0011_xp_guardada.sql'),
  ('0012_xp_guardada_por_ganancia.sql')
ON CONFLICT (name) DO NOTHING;

COMMIT;

-- ── Verificación (ejecútala después; debe devolver 5 filas en "ok") ──
SELECT 'personaje.personaje_en_centro_pokemon' AS objeto,
       EXISTS (SELECT 1 FROM information_schema.columns
                WHERE table_schema = 'juego' AND table_name = 'personaje'
                  AND column_name = 'personaje_en_centro_pokemon') AS ok
UNION ALL SELECT 'partida_intervencion', to_regclass('juego.partida_intervencion') IS NOT NULL
UNION ALL SELECT 'partida_xp', to_regclass('juego.partida_xp') IS NOT NULL
UNION ALL SELECT 'partida_xp_reparto', to_regclass('juego.partida_xp_reparto') IS NOT NULL
UNION ALL SELECT 'personaje_pokemon_xp_guardada (id_xp_guardada)',
       EXISTS (SELECT 1 FROM information_schema.columns
                WHERE table_schema = 'juego' AND table_name = 'personaje_pokemon_xp_guardada'
                  AND column_name = 'id_xp_guardada');
