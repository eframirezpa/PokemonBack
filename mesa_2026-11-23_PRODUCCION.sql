-- - Se puede ejecutar más de una vez sin daño (IF NOT EXISTS y comprobaciones).
-- - Solo agrega columnas y tablas nuevas: no borra ni modifica datos existentes.
-- - Al final las anota en juego.schema_migrations, para que un
--   `npm run migrate` contra producción no intente aplicarlas de nuevo.
