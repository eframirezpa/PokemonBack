-- Una fila por ganancia aplazada (no una por Pokémon). Cada ganancia de
-- experiencia sube como máximo un nivel; si dos ganancias aplazadas se
-- juntaran en una fila contarían como una sola. Ver lib/xp.js (partirXp).
--
-- Segura de repetir: solo quita la clave primaria si todavía es la vieja
-- (id_personaje_pokemon); si ya es id_xp_guardada no toca nada.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
      FROM information_schema.table_constraints tc
      JOIN information_schema.key_column_usage k
        ON k.constraint_name = tc.constraint_name AND k.table_schema = tc.table_schema
     WHERE tc.table_schema = '{{schema}}' AND tc.table_name = 'personaje_pokemon_xp_guardada'
       AND tc.constraint_type = 'PRIMARY KEY' AND k.column_name = 'id_personaje_pokemon'
  ) THEN
    ALTER TABLE "{{schema}}"."personaje_pokemon_xp_guardada"
      DROP CONSTRAINT personaje_pokemon_xp_guardada_pkey;
  END IF;
END $$;
ALTER TABLE "{{schema}}"."personaje_pokemon_xp_guardada"
  ADD COLUMN IF NOT EXISTS id_xp_guardada integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
CREATE INDEX IF NOT EXISTS personaje_pokemon_xp_guardada_pokemon_idx
  ON "{{schema}}"."personaje_pokemon_xp_guardada" (id_personaje_pokemon);
